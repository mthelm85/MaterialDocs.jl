"""Validate a hex color string."""
function _validate_hex(hex::String, field::String, path::String)
    if !occursin(r"^#[0-9A-Fa-f]{6}$", hex)
        throw(ArgumentError("Invalid hex color \"$hex\" for $field in $path"))
    end
end

"""Format a string as a TOML quoted string."""
function _toml_str(s::String)::String
    # TOML basic strings use double quotes; escape special chars
    escaped = replace(s,
        '\\' => "\\\\",
        '"' => "\\\"",
        '\n' => "\\n",
        '\t' => "\\t",
    )
    "\"$escaped\""
end
